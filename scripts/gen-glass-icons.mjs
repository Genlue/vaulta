// Regenerate the host's icon snapshot from GlassDesign's icon table.
// Usage: node scripts/gen-glass-icons.mjs <GlassDesign>/控件/src/base/icon.rs <out>/icons.js
// The web adapter only accepts built-in icon keys, so the host needs the same
// kebab-case inventory with the same 24-viewBox path markup.
import { readFile, writeFile } from 'node:fs/promises';

const [source, output] = process.argv.slice(2);
if (!source || !output) throw new Error('usage: gen-glass-icons.mjs <icon.rs> <icons.js>');

const rust = await readFile(source, 'utf8');
const table = rust.slice(rust.indexOf('pub fn path'));
// Entries appear both as `"name" => r#"…"#,` and as a braced block.
const entry = /"([a-z0-9-]+)"\s*=>\s*(?:\{\s*)?r#"([\s\S]*?)"#/g;
const glyphs = {};
for (const [, name, path] of table.matchAll(entry)) {
  if (Object.hasOwn(glyphs, name)) throw new Error(`duplicate icon: ${name}`);
  glyphs[name] = path;
}
if (!Object.keys(glyphs).length) throw new Error('no icon paths found in icon.rs');

const body = Object.entries(glyphs).map(([name, path]) => `  ${JSON.stringify(name)}: ${JSON.stringify(path)},`).join('\n');
await writeFile(output, `// SVG paths from GlassDesign 控件/src/base/icon.rs (see LICENSE).\n// Generated by scripts/gen-glass-icons.mjs; do not edit by hand.\nexport const glyphs = {\n${body}\n};\n`, 'utf8');
console.log(`icons.js: ${Object.keys(glyphs).length} glyphs from ${source}`);
